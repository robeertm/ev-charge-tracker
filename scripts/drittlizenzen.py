#!/usr/bin/env python3
"""Write THIRD-PARTY-NOTICES.md: every third-party component with its licence.

Sources:
1. the Python packages named in ``requirements.txt`` and
   ``requirements-vehicles.txt`` plus everything pip installs for them (the
   transitive closure), read from the installed package metadata of the
   environment this script runs in: licence expression, version and the licence
   files that ship with each package;
2. the browser libraries under ``static/vendor/`` (one directory per library,
   named ``<library>-<version>``, each with its licence file);
3. the pieces of the container image that are not Python packages.

Run it in a throwaway environment that has what the Dockerfile installs, for
example in a container (the connectors need Python 3.12)::

    docker run --rm --cpus 2 -v "$PWD:/src:ro" python:3.12-slim sh -c '
      cd /tmp && python -m venv v && . v/bin/activate &&
      grep -v "^saic-ismart-client-ng" /src/requirements-vehicles.txt > rv.txt &&
      pip install -q -r /src/requirements.txt -r rv.txt dacite httpx tenacity &&
      pip install -q --no-deps "$(grep "^saic-ismart-client-ng" /src/requirements-vehicles.txt | sed "s/#.*//")" &&
      python -I /src/scripts/drittlizenzen.py' > THIRD-PARTY-NOTICES.md

``tests/test_third_party_notices.py`` fails when a dependency listed in the
requirement files or a vendored library is missing from the generated file.
"""
from __future__ import annotations

import hashlib
import importlib.metadata as md
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Packages that pip installs but that are not part of the application.
SKIP = {"pip", "setuptools", "wheel"}

# SPDX identifiers for packages whose metadata carries a licence text or only a
# classifier instead of a licence expression (checked against the licence
# files of the installed versions).
SPDX_FALLBACK = {
    "blinker": "MIT",
    "contourpy": "BSD-3-Clause",
    "cycler": "BSD-3-Clause",
    "itsdangerous": "BSD-3-Clause",
    "jinja2": "BSD-3-Clause",
    "kiwisolver": "BSD-3-Clause",
    "matplotlib": "PSF-2.0-based (Matplotlib licence)",
}

# Spellings of the same licence found in package metadata, mapped to SPDX.
NORMALISE = {
    "MIT License": "MIT",
    "MIT license": "MIT",
    "License :: OSI Approved :: MIT License": "MIT",
    "Apache 2.0": "Apache-2.0",
    "Python Software Foundation License": "PSF-2.0",
    "PSFL": "PSF-2.0",
    "3-Clause BSD License": "BSD-3-Clause",
    "BSD License": "BSD-3-Clause",
}

# Browser libraries under static/vendor/: directory -> (name, SPDX, copyright)
VENDORED = {
    "bootstrap": ("Bootstrap", "MIT", "Copyright (c) 2011-2024 The Bootstrap Authors"),
    "bootstrap-icons": ("Bootstrap Icons", "MIT", "Copyright (c) 2019-2024 The Bootstrap Authors"),
    "leaflet": ("Leaflet", "BSD-2-Clause", "Copyright (c) 2010-2023, Volodymyr Agafonkin; "
                "Copyright (c) 2010-2011, CloudMade"),
    "leaflet.markercluster": ("Leaflet.markercluster", "MIT", "Copyright 2012 David Leaver"),
    "chartjs": ("Chart.js", "MIT", "Copyright (c) 2014-2024 Chart.js Contributors"),
    "chartjs-adapter-date-fns": ("chartjs-adapter-date-fns (with date-fns)", "MIT",
                                 "Copyright (c) 2019 Chart.js Contributors; date-fns: Copyright (c) 2021 Sasha Koss and Lesha Koss"),
}

KOPF = """# Third-party notices

EV Charge Tracker is built on the work of others. This file lists the
third-party components that are part of the application and of its container
image, with their licences. The application's own licence is in
[LICENSE](LICENSE); it does not limit the rights these licences grant for their
components.

The list is generated by `scripts/drittlizenzen.py` from `requirements.txt`,
`requirements-vehicles.txt`, `static/vendor/` and the installed package
metadata. Python dependencies are installed by pip and are not modified.

## Browser libraries (bundled in `static/vendor/`)

These files are served by the app itself, unmodified except that the trailing
source-map comment lines were removed. Each library directory holds its own
licence file.

{vendored}

## Container image

The container image (see `Dockerfile`) is based on the official `python` image:
**Python** under the Python Software Foundation License 2.0
(<https://docs.python.org/3/license.html>) and the Debian packages of that base
image, each under its own licence (`/usr/share/doc/<package>/copyright` inside
the image).

## Python packages

Every package pip installs for the application, including the optional vehicle
connectors that the container image carries. The licence texts follow below.

"""


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def req_names() -> list[str]:
    out = []
    for fname in ("requirements.txt", "requirements-vehicles.txt"):
        for line in (ROOT / fname).read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                out.append(norm(re.split(r"[<>=!~;\[ ]", line, maxsplit=1)[0]))
    return sorted(set(out))


def vendored() -> list[tuple[str, str, str, str, str]]:
    """(directory, name, version, spdx, copyright) of every vendored library."""
    out = []
    for d in sorted((ROOT / "static" / "vendor").iterdir()):
        if not d.is_dir():
            continue
        m = re.match(r"(.+)-(\d+(?:\.\d+)+)$", d.name)
        if not m or m.group(1) not in VENDORED:
            raise SystemExit(f"static/vendor/{d.name}: add it to VENDORED in {Path(__file__).name}")
        name, spdx, copyright_ = VENDORED[m.group(1)]
        out.append((d.name, name, m.group(2), spdx, copyright_))
    return out


def closure(roots: list[str]) -> dict[str, md.Distribution]:
    try:
        from packaging.requirements import Requirement
    except ImportError:  # pragma: no cover - packaging comes with the connectors
        raise SystemExit("run this script in an environment with `packaging` installed")
    installed = {norm(d.metadata["Name"]): d for d in md.distributions()}
    seen: dict[str, md.Distribution] = {}
    todo = [(r, ()) for r in roots]
    done: set[tuple[str, tuple]] = set()
    while todo:
        n, extras = todo.pop()
        if (n, extras) in done or n in SKIP:
            continue
        done.add((n, extras))
        d = installed.get(n)
        if d is None:
            if n in roots:
                raise SystemExit(f"{n} is not installed: install the requirement files first")
            continue  # extra or platform-specific dependency of another OS
        seen[n] = d
        for r in d.requires or []:
            req = Requirement(r)
            if req.marker is not None and not any(
                    req.marker.evaluate({"extra": e}) for e in ("", *extras)):
                continue
            todo.append((norm(req.name), tuple(sorted(req.extras))))
    return seen


def licence_expression(d: md.Distribution) -> str:
    meta = d.metadata
    n = norm(meta["Name"])
    expr = (meta.get("License-Expression") or "").strip()
    if expr:
        return expr
    if n in SPDX_FALLBACK:
        return SPDX_FALLBACK[n]
    lic = (meta.get("License") or "").strip()
    if lic and len(lic) <= 60 and "\n" not in lic:
        return NORMALISE.get(lic, lic)
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or []
                   if c.startswith("License ::")]
    found = ", ".join(classifiers) or "see licence file"
    return NORMALISE.get(found, found)


def licence_files(d: md.Distribution) -> list[tuple[str, str]]:
    """Licence files of one installed package.

    Everything under ``<dist-info>/licenses/`` (it carries the licences of
    components bundled in the package) plus licence-named files directly in
    ``<dist-info>/``.
    """
    out = []
    for f in d.files or []:
        parts = f.parts
        if not parts[0].endswith(".dist-info") or len(parts) < 2:
            continue
        if parts[1] == "licenses":
            wanted = len(parts) > 2
        else:
            wanted = len(parts) == 2 and parts[-1].upper().startswith(
                ("LICENSE", "LICENCE", "COPYING", "NOTICE"))
        if not wanted:
            continue
        p = Path(d.locate_file(f))
        if p.is_file():
            label = "/".join(parts[2:] if parts[1] == "licenses" else parts[1:])
            out.append((label, p.read_text(encoding="utf-8", errors="replace").strip()))
    return sorted(out)


def _copyleft_note(names: list[str]) -> str:
    if not names:
        return ""
    return ("\n\n## Notes on copyleft licences\n\n"
            + ", ".join(names) + ": used as separately installed, unmodified "
            "libraries. The licences allow replacing them: install another version "
            "with pip and the application uses that one. The full licence texts "
            "follow below.")


def main() -> int:
    vlines = [f"- **{name}** {version} — {spdx} — {copy} "
              f"(`static/vendor/{d}/`)" for d, name, version, spdx, copy in vendored()]
    dists = closure(req_names())
    lines, texts, copyleft = [], {}, []
    for n in sorted(dists):
        d = dists[n]
        name = d.metadata["Name"]
        expr = licence_expression(d)
        if re.search(r"\b(L?GPL|MPL)", expr) and " OR " not in expr:
            copyleft.append(f"`{name}` ({expr})")
        url = (d.metadata.get("Home-page") or "").strip()
        if not url:
            for pu in d.metadata.get_all("Project-URL") or []:
                if pu.lower().startswith(("homepage", "source", "repository")):
                    url = pu.split(",", 1)[1].strip()
                    break
        lines.append(f"- `{name}` {d.version} — {expr}"
                     + (f" — <{url}>" if url else ""))
        for fname, text in licence_files(d):
            if text:
                h = hashlib.sha256(text.encode()).hexdigest()
                texts.setdefault(h, (text, []))[1].append(f"{name} {d.version} ({fname})")
    # Licence texts of the vendored browser libraries.
    for d, name, version, _spdx, _copy in vendored():
        for f in sorted((ROOT / "static" / "vendor" / d).glob("*")):
            if f.is_file() and f.name.upper().startswith(("LICENSE", "LICENCE", "MIT-LICEN")):
                text = f.read_text(encoding="utf-8", errors="replace").strip()
                h = hashlib.sha256(text.encode()).hexdigest()
                texts.setdefault(h, (text, []))[1].append(f"{name} {version} ({f.name})")
    out = [KOPF.replace("{vendored}", "\n".join(vlines)), "\n".join(lines),
           _copyleft_note(copyleft), "\n\n## Licence texts\n"]
    for text, who in sorted(texts.values(), key=lambda t: sorted(t[1])[0].lower()):
        out.append("\n---\n\nUsed by: " + ", ".join(sorted(set(who)))
                   + "\n\n```text\n" + text + "\n```\n")
    sys.stdout.write("".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
